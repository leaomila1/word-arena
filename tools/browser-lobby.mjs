import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const W = 'http://127.0.0.1:8080';
const host = await (await b.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
const errs = []; host.on('pageerror', e => errs.push('host:' + e.message));
await host.goto(W + '/index.html'); await host.screenshot({ path: '/tmp/home.png' }); await host.click('#host'); await host.waitForURL(/host.html/);
await host.waitForFunction(() => document.querySelector('#code').textContent.length === 6);
const code = await host.textContent('#code');
const phone = async (name) => { const c = await b.newContext({ viewport: { width: 360, height: 800 } }); const p = await c.newPage(); p.on('pageerror', e => errs.push(name + ':' + e.message)); await p.goto(`${W}/play.html?code=${code}`); await p.fill('#name', name); await p.click('button[type=submit]'); return p; };
const a = await phone('Ann'), bob = await phone('Bob'), dup = await phone('ann');
await host.waitForTimeout(800);
console.log('count:', await host.textContent('#count'), '| dup msg:', await dup.textContent('#msg'));
console.log('ann view:', await a.textContent('[data-view=wait] h2'));
await host.screenshot({ path: '/tmp/host-lobby.png' }); await a.screenshot({ path: '/tmp/phone-wait.png' });
host.once('dialog', d => d.accept()); await host.click('[aria-label="Remove Bob"]'); await host.waitForTimeout(600);
console.log('after kick:', await host.textContent('#count'), '| bob sees:', await bob.textContent('#closedText'));
await a.reload(); await a.waitForTimeout(800); console.log('ann after reload:', await a.textContent('#me'), 'count', await host.textContent('#count'));
await host.reload(); await host.waitForTimeout(800); console.log('host after reload count:', await host.textContent('#count'));
console.log('errors:', errs.length ? errs : 'none');
await b.close();
