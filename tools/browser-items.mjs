import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const W = 'http://127.0.0.1:8080', errs = [];
const ctx = async o => { const c = await b.newContext(o); await c.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: "export const WORKER_URL = 'http://127.0.0.1:8787';" })); return c; };
let fails = 0; const check = (n, ok, x = '') => { console.log(ok ? 'PASS' : 'FAIL', n, x); if (!ok) fails++; };
const host = await (await ctx({ viewport: { width: 1920, height: 1080 } })).newPage(); host.on('pageerror', e => errs.push('host:' + e.message));
await host.goto(W + '/index.html'); await host.click('#host'); await host.waitForURL(/host.html/);
await host.waitForFunction(() => document.querySelector('#code').textContent.length === 6);
const code = await host.textContent('#code');
const mk = async n => { const p = await (await ctx({ viewport: { width: 390, height: 844 } })).newPage(); p.on('pageerror', e => errs.push(n + ':' + e.message)); await p.goto(`${W}/play.html?code=${code}`); await p.fill('#name', n); await p.click('button[type=submit]'); return p; };
const a = await mk('Ann'); await a.waitForSelector('[data-view=wait]:not([hidden])');
await host.click('label:has(input[value=contexto])'); await host.click('#start');
await a.waitForSelector('[data-view=round] input', { timeout: 7000 });
check('PIN + QR on top during round', (await host.textContent('#codeMini')) === code && !!(await host.$('#qrMini svg')));
const late = await mk('Bo');
check('late joiner plays right away', !!(await late.waitForSelector('[data-view=round] input', { timeout: 5000 }).catch(() => null)));
const R = '[data-view=round]';
for (const w of ['food', 'music', 'house', 'water', 'family']) { await a.fill(`${R} input`, w); await a.press(`${R} input`, 'Enter'); await a.waitForTimeout(1650); }
check('gift button after 5 guesses', await a.isVisible('.gift'));
await a.click('.gift'); await a.waitForTimeout(1700);
const card = await a.textContent('.item-card');
check('item card shown', /Secret letter|Next hint|close word|Double/.test(card), card);
await a.screenshot({ path: '/tmp/items-phone.png' });
await host.waitForTimeout(1300);
check('host feed shows box line', /🎁 Ann got/.test(await host.textContent('.feed')));
await host.waitForSelector('.hints .hint', { timeout: 30000 });
const chip = await host.textContent('.hints .hint');
check('hint chip has no icon', !/[🗂️🖼️🔤💡]/u.test(chip) && !(await host.textContent('.hints').then(t => t.includes('Hints'))), chip);
await host.screenshot({ path: '/tmp/items-host.png' });
host.once('dialog', d => d.accept()); await host.click('#endNow');
await host.waitForSelector('[data-view=reveal]:not([hidden])', { timeout: 6000 });
check('no scoreboard straight away', !(await host.$('.scoreboard')));
await host.waitForSelector('.scoreboard li', { timeout: 10000 });
const sb = await host.textContent('.scoreboard');
check('auto scoreboard with gains + NEW', /Ann/.test(sb) && /Bo/.test(sb) && /NEW/.test(sb), sb.replace(/\s+/g, ' ').slice(0, 160));
await host.screenshot({ path: '/tmp/items-scoreboard.png' });
await host.click('.scoreboard .btn--go');
check('Next round from scoreboard', !!(await host.waitForSelector('.fx-count', { timeout: 4000 }).catch(() => null)));
check('no page errors', errs.length === 0, errs.join(' | '));
console.log(fails ? `${fails} FAILED` : 'ALL PASS'); await b.close(); process.exit(fails ? 1 : 0);
