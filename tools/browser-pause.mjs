import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const W = 'http://127.0.0.1:8080', errs = [];
const ctx = async o => { const c = await b.newContext(o); await c.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: "export const WORKER_URL = 'http://127.0.0.1:8787';" })); return c; };
let fails = 0; const check = (n, ok, x = '') => { console.log(ok ? 'PASS' : 'FAIL', n, x); if (!ok) fails++; };
const hc = await ctx({ viewport: { width: 1920, height: 1080 } });
let host = await hc.newPage(); host.on('pageerror', e => errs.push('host:' + e.message));
await host.goto(W + '/index.html'); await host.click('#host'); await host.waitForURL(/host.html/);
await host.waitForFunction(() => document.querySelector('#code').textContent.length === 6);
const code = await host.textContent('#code');
const ph = await (await ctx({ viewport: { width: 390, height: 844 } })).newPage(); ph.on('pageerror', e => errs.push('phone:' + e.message));
await ph.goto(`${W}/play.html?code=${code}`); await ph.fill('#name', 'Ann'); await ph.click('button[type=submit]'); await ph.waitForSelector('[data-view=wait]:not([hidden])');
await host.click('label:has(input[value=contexto])'); await host.click('#start');
await ph.waitForSelector('[data-view=round] input', { timeout: 7000 }); await host.waitForTimeout(1500);
await host.click('#pause'); await host.waitForSelector('.fx-pause');
check('phone shows paused', !!(await ph.waitForSelector('.fx-pause', { timeout: 2000 }).catch(() => null)));
const t1 = await host.textContent('#timer'); await host.waitForTimeout(2500); const t2 = await host.textContent('#timer');
check('host timer frozen while paused', t1 === t2, `${t1} → ${t2}`);
check('button says Continue', (await host.textContent('#pause')).includes('Continue'));
await host.screenshot({ path: '/tmp/pause-host.png' }); await ph.screenshot({ path: '/tmp/pause-phone.png' });
await host.click('#pause');
await host.waitForFunction(() => !document.querySelector('.fx-pause'));
check('phone overlay gone after Continue', !!(await ph.waitForFunction(() => !document.querySelector('.fx-pause'), null, { timeout: 2000 }).catch(() => null)));
await host.waitForTimeout(2200);
check('timer runs again', (await host.textContent('#timer')) !== t2);
await ph.fill('[data-view=round] input', 'food'); await ph.press('[data-view=round] input', 'Enter'); await ph.waitForTimeout(800);
host.once('dialog', d => d.accept()); await host.click('#endNow');
await host.waitForSelector('[data-view=reveal]:not([hidden])', { timeout: 6000 });
await host.click('[data-view=reveal] .js-scores'); await host.waitForSelector('.scoreboard li');
check('scoreboard lists Ann', /Ann/.test(await host.textContent('.scoreboard')), await host.textContent('.scoreboard li'));
await host.screenshot({ path: '/tmp/scoreboard.png' });
await host.close();
host = await hc.newPage(); host.on('pageerror', e => errs.push('host2:' + e.message));
await host.goto(W + '/index.html');
check('index offers way back', (await host.textContent('#back')).includes(code));
await host.click('#back'); await host.waitForSelector('[data-view=reveal]:not([hidden])', { timeout: 6000 });
check('reopened host lands in same room', (await host.textContent('#code')) === code);
await host.click('#toLobby'); await host.click('[data-view=lobby] .js-scores');
check('scores kept after reopen', /Ann/.test(await host.textContent('.scoreboard')));
check('no page errors', errs.length === 0, errs.join(' | '));
console.log(fails ? `${fails} FAILED` : 'ALL PASS'); await b.close(); process.exit(fails ? 1 : 0);
