"""Build server data from content/words.csv (approved rows only).
Outputs: server/data/vocab.txt, server/data/ranks.bin, server/data/contexto-data.js,
server/data/davini-data.js, tools/report_neighbours.md
Needs: pip install spacy numpy wordfreq english-words + en_core_web_lg (from the spaCy GitHub release)."""
import csv, json, re, sys, pathlib
import numpy as np, spacy
from wordfreq import top_n_list
from english_words import get_english_words_set

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / 'server' / 'data'
VOCAB_CAP, TOP = 20000, 5000
BLOCK = {'naked','nude','nudes','nudity','porno','xxx','erotic','orgasm','horny','lesbian','gay','incest','underage','fetish','bondage','hentai','milf','stripper','masturbation','masturbate','dildo','condom','condoms','genital','genitals','breast','breasts','nipple','nipples','butt','booty','anal','oral','sperm','semen','erection','hooker','prostitute','prostitution','escort','escorts','kinky','seductive','sensual','lust','slutty','thong','lingerie','bra','panties','cocaine','heroin','meth','weed','marijuana','suicide','kill','killed','killing','murder','gun','guns','rifle','bomb','bombs','terrorist','terrorism','nazi','hitler','drunk','vodka','beer','alcohol','cigarette','cigarettes','teen','teens','hot','sexual','sexually','cock','balls','bastards','motherfucker','fucking','fucked','shitty','bullshit','wtf','omg','lol','lmao',''}
BLOCK |= {'fuck','shit','cunt','bitch','asshole','dick','pussy','whore','slut','porn','sex','sexy','ass','cum','tit','tits','nigga','nigger','fag','faggot','rape','penis','vagina','boobs','damn','hell','bastard','crap','piss'}

rows = [r for r in csv.DictReader(open(ROOT / 'content/words.csv', encoding='utf-8')) if r['teacher_approved'] == 'yes']
nlp = spacy.load('en_core_web_lg', disable=['parser', 'ner'])
DICT = get_english_words_set(['web2', 'gcide'], lower=False)
has_vec = lambda w: nlp.vocab.has_vector(w)

# Guessable vocabulary: most frequent English words that have a vector.
vocab = []
seen = set()
cands = [w for w in top_n_list('en', 120000) if re.fullmatch(r'[a-z]{2,}', w) and w not in BLOCK and has_vec(w)]
lemmas = {}
for doc in nlp.pipe(cands, batch_size=2000):
    lemmas[doc.text] = doc[0].lemma_.lower() if len(doc) else doc.text
for w in cands:  # real dictionary word (or inflection of one) → drops names, slang, abbreviations
    if w in seen or not (w in DICT or lemmas.get(w) in DICT) or lemmas.get(w) in BLOCK: continue
    vocab.append(w); seen.add(w)
    if len(vocab) >= VOCAB_CAP: break
targets = []
for r in rows:
    w = r['word'].lower()
    if r['contexto'] == 'no' or not has_vec(w):
        r['contexto'] = 'no'; continue
    if w not in seen: vocab.append(w); seen.add(w)
    r['contexto'] = 'yes'; targets.append(r)

M = np.stack([nlp.vocab.get_vector(w) for w in vocab]).astype(np.float32)
M /= np.linalg.norm(M, axis=1, keepdims=True) + 1e-9
idx = {w: i for i, w in enumerate(vocab)}
assert len(vocab) < 65536

tops, report = [], ['# 20 nearest words per Contexto target', '', 'Check each line: do the neighbours make sense? Reply with any target that looks wrong.', '']
for t in targets:
    w = t['word'].lower()
    sims = M @ M[idx[w]]
    order = np.argsort(-sims, kind='stable')
    order = np.concatenate([[idx[w]], order[order != idx[w]]])[:TOP]  # answer is always rank 1
    tops.append(order.astype('<u2'))
    report.append(f"- **{w}** ({t['context']}): " + ', '.join(vocab[i] for i in order[1:21]))

DATA.mkdir(parents=True, exist_ok=True)
(DATA / 'vocab.txt').write_text('\n'.join(vocab), encoding='utf-8')
(np.concatenate(tops) if tops else np.zeros(0, '<u2')).tofile(DATA / 'ranks.bin')
meta = [{k: t[k] for k in ('id', 'word', 'context', 'culture_note_en', 'culture_note_th')} for t in targets]
for m in meta: m['word'] = m['word'].lower()
(DATA / 'contexto-data.js').write_text(
    "// GENERATED by tools/build_content.py — do not edit.\n"
    "import vocabText from './vocab.txt';\nimport ranksBuf from './ranks.bin';\nimport { loadRankData } from '../src/games/rankdata.js';\n"
    f"export const TOP = {TOP};\nexport const targets = {json.dumps(meta, ensure_ascii=False)};\n"
    "export const { vocabIndex, getRanks } = loadRankData(vocabText, ranksBuf, targets, TOP);\n", encoding='utf-8')
puzzles = [{'id': r['id'], 'context': r['context'], 'category': r['category'], 'answer': r['word'].lower(), 'clue_text': r['clue_text'],
            'emoji': [r['emoji1'], r['emoji2'], r['emoji3']], 'culture_note_en': r['culture_note_en'], 'culture_note_th': r['culture_note_th']} for r in rows]
(DATA / 'davini-data.js').write_text("// GENERATED by tools/build_content.py — do not edit.\nexport const puzzles = " + json.dumps(puzzles, ensure_ascii=False, indent=0) + ";\n", encoding='utf-8')
(ROOT / 'tools' / 'report_neighbours.md').write_text('\n'.join(report) + '\n', encoding='utf-8')
no = [r['word'] for r in rows if r['contexto'] == 'no']
print(f'vocab={len(vocab)} contexto_targets={len(targets)} davini={len(puzzles)} no_vector={no}')
print('ranks.bin bytes', (DATA / 'ranks.bin').stat().st_size)
# write contexto yes/no back to the CSV
allrows = list(csv.DictReader(open(ROOT / 'content/words.csv', encoding='utf-8')))
flag = {r['id']: r['contexto'] for r in rows}
for r in allrows: r['contexto'] = flag.get(r['id'], r['contexto'])
w = csv.DictWriter(open(ROOT / 'content/words.csv', 'w', newline='', encoding='utf-8'), fieldnames=allrows[0].keys()); w.writeheader(); w.writerows(allrows)
