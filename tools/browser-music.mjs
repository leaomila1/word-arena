import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const W = 'http://127.0.0.1:8080', errs = [];
const ctx = async o => { const c = await b.newContext(o); await c.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: "export const WORKER_URL = 'http://127.0.0.1:8787';" })); return c; };
let fails = 0; const check = (n, ok, x = '') => { console.log(ok ? 'PASS' : 'FAIL', n, x); if (!ok) fails++; };
const host = await (await ctx({ viewport: { width: 1920, height: 1080 } })).newPage(); host.on('pageerror', e => errs.push(e.message));
await host.goto(W + '/index.html'); await host.click('#host'); await host.waitForURL(/host.html/);
await host.waitForFunction(() => document.querySelector('#code').textContent.length === 6);
const code = await host.textContent('#code');
const ph = await (await ctx({ viewport: { width: 390, height: 844 } })).newPage(); ph.on('pageerror', e => errs.push('phone:' + e.message));
await ph.goto(`${W}/play.html?code=${code}`); await ph.fill('#name', 'Ann'); await ph.click('button[type=submit]');
const on = () => host.evaluate(async () => (await import('./core/sfx.js')).gameMusicOn());
await host.click('#start'); await host.waitForSelector('.fx-count');
check('no game music during 3-2-1', !(await on()));
await host.waitForFunction(() => !document.querySelector('.fx-count'), null, { timeout: 6000 }); await host.waitForTimeout(300);
check('music on after GO', await on());
const phoneMusic = await ph.evaluate(async () => (await import('./core/sfx.js')).gameMusicOn());
check('phone has no music', !phoneMusic);
await host.click('#pause'); await host.waitForSelector('.fx-pause');
check('music off while paused', !(await on()));
await host.click('#pause'); await host.waitForFunction(() => !document.querySelector('.fx-pause')); await host.waitForTimeout(300);
check('music back after Continue', await on());
await host.click('.mute'); check('mute stops music', !(await on()));
await host.click('.mute'); await host.waitForTimeout(200); check('unmute restarts music', await on());
host.once('dialog', d => d.accept()); await host.click('#endNow');
await host.waitForSelector('[data-view=reveal]:not([hidden])', { timeout: 6000 });
check('music off at reveal', !(await on()));
check('no page errors', errs.length === 0, errs.join(' | '));
console.log(fails ? `${fails} FAILED` : 'ALL PASS'); await b.close(); process.exit(fails ? 1 : 0);
